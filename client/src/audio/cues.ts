// Audio manifest: the single source of truth for every sound the TV plays.
//
// Swapping in Patrick's real tracks is a one-line change per cue:
//   lobby: { src: placeholder('music-lobby'), ... }   ->   lobby: { src: real('music-lobby'), ... }
// real('music-lobby') looks for client/public/audio/music-lobby.ogg, then .mp3.
// If a file is missing or fails to load, that cue is silently skipped.
// See docs/team/music-briefs.md for the filename and spec of every cue.
import type { Phase } from '../../../shared/types.ts';
import type { SfxKey } from './index.ts';

/** Files Patrick drops into client/public/audio/ (ogg first: it loops gaplessly; mp3 as fallback). */
export const real = (name: string): string[] => [`/audio/${name}.ogg`, `/audio/${name}.mp3`];
/** Generated by client/src/audio/generate-placeholders.sh. */
export const placeholder = (name: string): string[] => [
  `/audio/placeholder/${name}.ogg`,
  `/audio/placeholder/${name}.mp3`,
];

export type MusicKey = 'lobby' | 'captioning' | 'voting' | 'results' | 'final';

export interface Cue {
  src: string[];
  /** 0..1, relative to the master volume. */
  volume: number;
  loop: boolean;
  /** Stingers only: dip the music while this plays. */
  duck?: boolean;
}

